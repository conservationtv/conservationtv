//! Renders a version-aware Rust SDK's `src/generated` from the `.generate` folder its `openapi-ts.config.ts` writes:
//! `operations.json` (the Client's operation tree) and `manifests/<source>.json` (one per generation job, by
//! `@conservationtv/versioned-api`'s `rust-manifest` plugin). Names and flat fields come from the manifests, which use
//! the same rules as the TypeScript SDK; this only renders them.
//!
//! `cargo run -p versioned-api-codegen -- --manifest .generate --out src/generated`

mod client;
mod contract;
mod manifest;
mod names;

use contract::Result;
use manifest::{CURRENT, Manifest, Operations};
use proc_macro2::TokenStream;
use std::path::{Path, PathBuf};

fn read<T: serde::de::DeserializeOwned>(path: &Path) -> Result<T> {
    let text =
        std::fs::read_to_string(path).map_err(|error| format!("{}: {error}", path.display()))?;
    serde_json::from_str(&text).map_err(|error| format!("{}: {error}", path.display()))
}

fn format(tokens: TokenStream, what: &str) -> Result<String> {
    let file = syn::parse2::<syn::File>(tokens)
        .map_err(|error| format!("{what}: generated invalid Rust: {error}"))?;
    Ok(prettyplease::unparse(&file))
}

fn write(path: &Path, contents: &str) -> Result<()> {
    std::fs::write(path, contents).map_err(|error| format!("{}: {error}", path.display()))
}

fn run(manifest_dir: &Path, out: &Path) -> Result<()> {
    let operations: Operations = read(&manifest_dir.join("operations.json"))?;
    let directory = manifest_dir.join("manifests");
    let mut files = std::fs::read_dir(&directory)
        .map_err(|error| format!("{}: {error}", directory.display()))?
        .map(|entry| {
            entry
                .map(|entry| entry.path())
                .map_err(|error| error.to_string())
        })
        .collect::<Result<Vec<PathBuf>>>()?;
    files.retain(|path| {
        path.extension()
            .is_some_and(|extension| extension == "json")
    });
    files.sort();

    let mut current = None;
    let mut versions = Vec::new();
    let mut rendered = Vec::new();
    for file in &files {
        let manifest: Manifest = read(file)?;
        let contract = contract::render(&manifest)?;
        let source = format(contract.tokens, &manifest.source)?;
        rendered.extend(contract.operations);
        if manifest.source == CURRENT {
            current = Some(source);
        } else {
            versions.push((contract.module, source));
        }
    }
    let client = format(client::render(&operations, &rendered)?, "client")?;

    if out.exists() {
        std::fs::remove_dir_all(out).map_err(|error| format!("{}: {error}", out.display()))?;
    }
    let versions_dir = out.join("versions");
    std::fs::create_dir_all(&versions_dir)
        .map_err(|error| format!("{}: {error}", versions_dir.display()))?;
    let mut modules = String::from(
        "//! Generated by versioned-api-codegen: one module per frozen operation contract. Do not edit.\n\n",
    );
    for (module, source) in &versions {
        write(&versions_dir.join(format!("{module}.rs")), source)?;
        modules.push_str(&format!("pub mod {module};\n"));
    }
    write(&versions_dir.join("mod.rs"), &modules)?;
    write(
        &out.join("current.rs"),
        current
            .as_deref()
            .ok_or("no manifest for the current spec")?,
    )?;
    write(&out.join("client.rs"), &client)?;
    write(
        &out.join("mod.rs"),
        "//! Generated by versioned-api-codegen. Do not edit.\n\npub mod client;\npub mod current;\npub mod versions;\n",
    )?;
    Ok(())
}

fn main() -> std::process::ExitCode {
    let mut args = std::env::args().skip(1);
    let (mut manifest, mut out) = (None, None);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--manifest" => manifest = args.next().map(PathBuf::from),
            "--out" => out = args.next().map(PathBuf::from),
            other => {
                eprintln!("unknown argument {other}");
                return std::process::ExitCode::FAILURE;
            }
        }
    }
    let (Some(manifest), Some(out)) = (manifest, out) else {
        eprintln!("usage: versioned-api-codegen --manifest <.generate> --out <src/generated>");
        return std::process::ExitCode::FAILURE;
    };
    match run(&manifest, &out) {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("versioned-api-codegen: {error}");
            std::process::ExitCode::FAILURE
        }
    }
}
