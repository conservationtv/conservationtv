// Renders a version-aware Swift SDK's generated sources from the `.generate` folder its `openapi-ts.config.ts` writes:
// `operations.json` (the Client's operation tree) and `manifests/<source>.json` (one per generation job, by
// `@conservationtv/versioned-api`'s `rust-manifest` plugin). Names and flat fields come from the manifests, which use
// the same rules as the TypeScript and Rust SDKs; types come from swift-openapi-generator. This only renders them.
//
// swift run --package-path <this package> versioned-api-codegen --manifest .generate --out <Sources/.../Generated>

import Foundation

func read(_ url: URL) throws -> JSON {
    do {
        return try JSON(parsing: try Data(contentsOf: url))
    } catch {
        throw CodegenError("\(url.path): \(error)")
    }
}

func write(_ contents: String, to url: URL) throws {
    try Data(contents.utf8).write(to: url)
}

func run(manifest: URL, out: URL) throws {
    let operations = try Operations(read(manifest.appendingPathComponent("operations.json")))
    let directory = manifest.appendingPathComponent("manifests")
    let files = try FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)
        .filter { $0.pathExtension == "json" }
        .sorted { $0.lastPathComponent < $1.lastPathComponent }

    var current: RenderedContract?
    var versions: [RenderedContract] = []
    for file in files {
        let contract = try renderContract(read(file))
        if contract.versioned { versions.append(contract) } else { current = contract }
    }
    guard let current else { throw CodegenError("no manifest for the current spec") }
    let client = try renderClient(operations, (versions + [current]).flatMap(\.operations))

    let manager = FileManager.default
    if manager.fileExists(atPath: out.path) { try manager.removeItem(at: out) }
    let versionsDirectory = out.appendingPathComponent("Versions")
    try manager.createDirectory(at: versionsDirectory, withIntermediateDirectories: true)
    try write(
        """
        // Generated by versioned-api-codegen. Do not edit.

        /// One namespace per frozen operation contract, each with the types and Params of that operation's version.
        public enum Versions {}

        """, to: out.appendingPathComponent("Versions.swift"))
    for contract in versions {
        try write(contract.swift, to: versionsDirectory.appendingPathComponent("\(contract.name).swift"))
    }
    try write(current.swift, to: out.appendingPathComponent("Current.swift"))
    try write(client, to: out.appendingPathComponent("Client.swift"))
}

var arguments = CommandLine.arguments.dropFirst().makeIterator()
var manifest: URL?
var out: URL?
while let argument = arguments.next() {
    switch argument {
    case "--manifest": manifest = arguments.next().map { URL(fileURLWithPath: $0) }
    case "--out": out = arguments.next().map { URL(fileURLWithPath: $0) }
    default:
        FileHandle.standardError.write(Data("unknown argument \(argument)\n".utf8))
        exit(1)
    }
}
guard let manifest, let out else {
    FileHandle.standardError.write(Data("usage: versioned-api-codegen --manifest <.generate> --out <Generated>\n".utf8))
    exit(1)
}
do {
    try run(manifest: manifest, out: out)
} catch {
    FileHandle.standardError.write(Data("versioned-api-codegen: \(error)\n".utf8))
    exit(1)
}
