/**
 * Writes src/generated/ui-theme.ts: the theme of @conservationtv/ui's stylesheet, as the CSS React Email's Tailwind
 * compiles the emails' classes against. The emails then share the web app's colours, type scale and radii by name
 * (`bg-card`, `text-muted-foreground`, `rounded-xl`), and follow it whenever this is run again.
 *
 * Only the theme comes across: `@theme` blocks and the light `:root` variables, from globals.css and the local
 * stylesheets it imports. Email clients have no base layer and no package stylesheets (Tailwind's own theme comes with
 * React Email), so those are left behind; and rem lengths become pixels, which every client sizes alike.
 *
 * Nor can an email switch variables by class: React Email resolves every variable to a fixed value as it inlines. So
 * each theme colour the `.dark` block redefines also comes across as a `dark-` colour holding its dark value
 * (`--color-dark-muted-foreground`), for the emails' `dark:` variants, which Tailwind writes as
 * `prefers-color-scheme` media queries.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generate, parse, type CssNode, type StyleSheet } from 'css-tree';

const ROOT_FONT_SIZE = 16;
const output = fileURLToPath(new URL('../src/generated/ui-theme.ts', import.meta.url));
const entry = fileURLToPath(import.meta.resolve('@conservationtv/ui/globals.css'));

/** The top-level nodes of a stylesheet and of the local stylesheets it imports, in order. */
function nodesOf(file: string): CssNode[] {
  const sheet = parse(readFileSync(file, 'utf8'), { positions: false });
  return topLevel(sheet).flatMap(node => {
    const target = importTarget(node);
    // Package stylesheets (tailwindcss, shadcn, fonts) are not part of the theme.
    if (target === undefined) return [node];
    return target.startsWith('.') ? nodesOf(resolve(dirname(file), target)) : [];
  });
}

function topLevel(sheet: CssNode): CssNode[] {
  return sheet.type === 'StyleSheet' ? (sheet satisfies StyleSheet).children.toArray() : [];
}

/** The light theme: `@theme` blocks and `:root` rules (of `:root, .dark { … }`, the light half). */
function lightPart(node: CssNode): string[] {
  if (node.type === 'Atrule' && node.name === 'theme') return [generate(node)];
  if (node.type === 'Rule' && selectorsOf(node).includes(':root')) return [`:root${generate(node.block)}`];
  return [];
}

/** The variables `.dark` alone redefines, by name. */
function darkVariables(nodes: CssNode[]): Map<string, string> {
  const declarations = nodes
    .filter(node => node.type === 'Rule' && selectorsOf(node).join(',') === '.dark')
    .flatMap(node => (node.type === 'Rule' ? node.block.children.toArray() : []));
  return new Map(
    declarations.flatMap(child =>
      child.type === 'Declaration' ? [[child.property, generate(child.value).trim()] as const] : []
    )
  );
}

/** A `dark-` theme colour for each theme colour drawn from a variable `.dark` redefines. */
function darkTheme(light: string, dark: Map<string, string>): string {
  const colours = [...light.matchAll(/--color-([\w-]+):\s*var\((--[\w-]+)\)/g)].flatMap(([, name, variable]) => {
    const value = dark.get(variable ?? '');
    return value === undefined ? [] : [`--color-dark-${name}: ${value};`];
  });
  return `@theme inline{${[...new Set(colours)].join('')}}`;
}

// complexity: only an `@import` with a prelude names a stylesheet; its target may be quoted, bare or in url().
function importTarget(node: CssNode): string | undefined {
  if (node.type !== 'Atrule' || node.name !== 'import' || !node.prelude) return undefined;
  const prelude = generate(node.prelude);
  return /^(?:url\()?['"]?([^'")\s]+)/.exec(prelude)?.[1];
}

function selectorsOf(node: CssNode): string[] {
  if (node.type !== 'Rule') return [];
  return generate(node.prelude)
    .split(',')
    .map(selector => selector.trim());
}

/** One declaration per line, so a change to the theme reads as a change to its lines. */
function lines(css: string): string {
  return css
    .replace(/\{/g, ' {\n  ')
    .replace(/;(?!\s*\})/g, ';\n  ')
    .replace(/;?\s*\}/g, ';\n}\n');
}

function remToPixels(css: string): string {
  return css.replace(/(-?\d*\.?\d+)rem\b/g, (_match, value: string) => `${Number(value) * ROOT_FONT_SIZE}px`);
}

const nodes = nodesOf(entry);
const light = nodes.flatMap(lightPart).join('');
const theme = lines(remToPixels(light + darkTheme(light, darkVariables(nodes))));
writeFileSync(
  output,
  `// Generated by scripts/generate.ts from @conservationtv/ui's globals.css: run \`pnpm generate\` here after changing it.\n\n` +
    `/** @conservationtv/ui's theme, for React Email's Tailwind: its \`@theme\` blocks, light \`:root\` variables and \`dark-\` colours. */\n` +
    `export const uiTheme = String.raw\`${theme}\`;\n`
);
console.info(`Wrote ${output}`);
