import type { Category } from './review.ts';

/**
 * How this repository's files come to be. Generated output is committed so every change to it is visible, and each
 * generator's input is reviewed instead: the routes behind an API's document, the document behind its SDK and CLI, the
 * Drizzle schema behind its migrations. Keep this in step with the generated paths in oxlint.config.ts.
 */
interface Rule {
  pattern: RegExp;
  category: Category;
  generator: string;
}

const rules: Rule[] = [
  { pattern: /(^|\/)pnpm-lock\.yaml$/, category: 'lockfile', generator: 'pnpm install' },
  { pattern: /\/contracts\/openapi\.json$/, category: 'contract', generator: 'api-contracts generate' },
  { pattern: /\/contracts\/snapshots\/[^/]+\.json$/, category: 'contract', generator: 'api-contracts snapshot' },
  { pattern: /^apps\/[^/]+\/sdk\/src\/(generated|versions)\//, category: 'generated', generator: 'openapi-ts: SDK' },
  { pattern: /^apps\/[^/]+\/cli\/src\/generated\//, category: 'generated', generator: 'openapi-ts: CLI' },
  { pattern: /^packages\/mediamtx\/src\/generated\//, category: 'generated', generator: 'openapi-ts: MediaMTX' },
  { pattern: /^apps\/controlplane\/infrastructure\/sdks\//, category: 'generated', generator: 'pulumi package add' },
  { pattern: /\/drizzle\/[^/]+\/snapshot\.json$/, category: 'generated', generator: 'drizzle-kit generate' },
  { pattern: /\/drizzle\/[^/]+\/migration\.sql$/, category: 'migration', generator: 'drizzle-kit generate' }
];

/** Files that name their generator in their first line, as umbrella's policy migrations and hey-api's output do. */
const generatedHeader = /^\+(?:\/\/|--|#|\/\*)\s*(?:This file is auto-generated by|Generated by|@generated)\s*(.*)$/;

export interface Classification {
  category: Category;
  generator: string | null;
}

/** The first line of a file the patch adds whole; other patches need not start at the top of the file. */
function headerLine(patch: string | null): string | undefined {
  if (!patch?.startsWith('@@ -0,0 +1')) return undefined;
  return patch.split('\n', 2)[1];
}

/** A path rule names the generator best; a header only says more of a migration or what looks like source code. */
export function classify(path: string, patch: string | null): Classification {
  const rule = rules.find(candidate => candidate.pattern.test(path));
  if (rule && rule.category !== 'migration') return { category: rule.category, generator: rule.generator };
  const header = headerLine(patch)?.match(generatedHeader);
  if (header) return { category: 'generated', generator: header[1]?.replace(/[.\s*/]+$/, '') || 'generator' };
  if (rule) return { category: rule.category, generator: rule.generator };
  return { category: 'source', generator: null };
}

/** The order files are read in, and how each kind is labelled. */
export const categories: readonly Category[] = ['source', 'migration', 'contract', 'generated', 'lockfile'];

export const categoryLabels = {
  source: 'Source code',
  migration: 'Migrations',
  contract: 'API contracts',
  generated: 'Generated',
  lockfile: 'Lockfile'
} satisfies Record<Category, string>;
