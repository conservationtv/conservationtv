import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { defineConfig, type UserConfig } from '@hey-api/openapi-ts';
import { flatParams } from './plugins/flat-params.plugin.js';
import { CURRENT, readOperations } from './plugins/operation-versions.js';
import { sdkClient } from './plugins/sdk-client.plugin.js';

// Generates this package's src/generated (the Client SDK, its types and Zod schemas) from the
// API's OpenAPI spec, and src/versions/<operationId>-vN (the BaseClient and version-suffixed Params for each frozen contract that
// Client and the CLI still need). The oldest versions kept are set in minimum-versions.ts.
// Run `pnpm generate` from the workspace root after changing a route, so the spec, SDK and CLI stay in step.
const spec = createRequire(import.meta.url).resolve('@conservationtv/gatekeeper/openapi.json');

const operations = readOperations(spec);
const snapshots = Map.groupBy(
  operations.versioned.filter(operation => operation.source !== CURRENT),
  operation => operation.source
);
// Each contract job cleans its own folder; this drops the folders of contracts no longer needed, and re-exports the
// Params of those that are. Version suffixes keep their names apart.
const versions = new URL('./src/versions/', import.meta.url);
rmSync(versions, { recursive: true, force: true });
mkdirSync(versions);
const exports = [...snapshots.keys()].map(source => `export * from './${source}/index.js';\n`);
writeFileSync(
  new URL('index.ts', versions),
  `// Generated by openapi-ts.config.ts\n\n${exports.join('') || 'export {};\n'}`
);

const sdk = {
  name: '@hey-api/sdk',
  includeInEntry: false,
  paramsStructure: 'flat',
  operations: {
    strategy: 'single',
    containerName: 'BaseClient',
    methods: 'instance',
    nesting: operation => operation.operationId!.split('.')
  }
} satisfies NonNullable<UserConfig['plugins']>[number];

const zod = {
  name: 'zod',
  metadata: true,
  // Match the Params exports: PascalCase, no `z` prefix, a `Schema` suffix.
  case: 'PascalCase',
  definitions: '{{name}}Schema',
  requests: {
    name: '{{name}}DataSchema',
    body: '{{name}}BodySchema',
    headers: '{{name}}HeadersSchema',
    path: '{{name}}PathSchema',
    query: '{{name}}QuerySchema'
  },
  responses: '{{name}}ResponseSchema'
} satisfies NonNullable<UserConfig['plugins']>[number];

export default defineConfig([
  {
    input: spec,
    output: { path: './src/generated', module: { extension: '.js' } },
    plugins: [
      '@hey-api/typescript',
      '@hey-api/client-fetch',
      { ...zod, includeInEntry: true },
      sdk,
      flatParams(),
      sdkClient({ operations })
    ]
  },
  // Only the operation version a contract defines, and the schemas they use. Its entry exports just their Params.
  ...[...snapshots].map(([source, defined]): UserConfig => ({
    input: { path: defined[0]!.document },
    output: { path: `./src/versions/${source}`, module: { extension: '.js' } },
    parser: { filters: { operations: { include: defined.map(operation => operation.key) }, orphans: false } },
    plugins: [
      { name: '@hey-api/typescript', includeInEntry: false },
      '@hey-api/client-fetch',
      { ...zod, includeInEntry: false },
      sdk,
      flatParams({ versionSuffix: true })
    ]
  }))
]);
